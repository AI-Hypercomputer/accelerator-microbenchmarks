_NUM_CPU_DEVICES = 8

# Force multiple virtual CPU devices so shard_map and checksum consensus can be
# tested without TPUs. Must run before the JAX backend is initialized; JAX
# raises an error if the backend has already been initialized.
jax.config.update("jax_num_cpu_devices", _NUM_CPU_DEVICES)
# Set CPU backend for fast testing without TPU requirements
jax.config.update("jax_platform_name", "cpu")


def _flip_bit(x, flat_index, bit):
  """Returns `x` with bit `bit` of element `flat_index` (row-major) flipped."""
  uint_dtype = checksum.get_bitcast_uint_dtype(x.dtype)
  u = jax.lax.bitcast_convert_type(x, uint_dtype).reshape(-1)
  u = u.at[flat_index].set(u[flat_index] ^ jnp.asarray(1 << bit, uint_dtype))
  return jax.lax.bitcast_convert_type(u.reshape(x.shape), x.dtype)


def _mesh(num_devices):
  return jax.sharding.Mesh(
      np.array(jax.devices()[:num_devices]), axis_names=("device",)
  )


def _replicated_with_fault(x, mesh, device_index=None, flat_index=0, bit=0):
  """Builds a P()-replicated array whose copy on one mesh device is corrupted.

  JAX does not check that the replicas of a replicated array agree, so this
  simulates a single-bit fault in one device's operand without any
  fault-injection code in the benchmark. With `device_index=None` all
  replicas are identical.

  Args:
    x: Host value to replicate.
    mesh: Mesh whose devices receive a replica.
    device_index: Position in `mesh.devices.flat` of the corrupted replica.
    flat_index: Row-major element index to corrupt.
    bit: Bit to flip in that element.

  Returns:
    A `jax.Array` with `NamedSharding(mesh, P())`.
  """
  x = jnp.asarray(x)
  bad = _flip_bit(x, flat_index, bit) if device_index is not None else x
  sharding = jax.sharding.NamedSharding(mesh, jax.sharding.PartitionSpec())
  buffers = [
      jax.device_put(bad if i == device_index else x, d)
      for i, d in enumerate(mesh.devices.flat)
  ]
  return jax.make_array_from_single_device_arrays(x.shape, sharding, buffers)


def _reference_chain(x, b, steps, in_dtype, out_dtype):
  """Plain-JAX reference for `steps` chain steps (same formula as the chain)."""
  x = jnp.asarray(x).astype(out_dtype)
  for _ in range(steps):
    x = jnp.dot(x.astype(in_dtype), jnp.asarray(b)).astype(out_dtype)
  return x


class _CorruptedInputGemmChained(matmul.GemmChainedBenchmark):
  """Starts the chain from X_{start_step} with one optionally corrupted replica.

  `generate_inputs()` computes X_{start_step} with `_reference_chain` and
  replicates it (and B) to every mesh device, corrupting the copy of
  `operand` ("x" or "b") on mesh device `device_index`. Running the remaining
  `config.chain_length` steps is equivalent to a fault injected after step
  `start_step` of a longer chain on that device only.
  """

  def __init__(
      self,
      *args,
      start_step=0,
      operand="x",
      device_index=None,
      flat_index=0,
      bit=0,
      **kwargs,
  ):
    super().__init__(*args, **kwargs)
    self._start_step = start_step
    self._operand = operand
    self._device_index = device_index
    self._flat_index = flat_index
    self._bit = bit

  def generate_inputs(self):
    x0, b = super().generate_inputs()
    b_host = np.asarray(b)
    xs = _reference_chain(
        np.asarray(x0),
        b_host,
        self._start_step,
        utils.parse_dtype(self.config.in_dtype),
        utils.parse_dtype(self.config.out_dtype),
    )
    x_bad = self._device_index if self._operand == "x" else None
    b_bad = self._device_index if self._operand == "b" else None
    return (
        _replicated_with_fault(
            xs, self.mesh, x_bad, self._flat_index, self._bit
        ),
        _replicated_with_fault(
            b_host, self.mesh, b_bad, self._flat_index, self._bit
        ),
    )


class InputsFnTest(absltest.TestCase):
  """Tests for `make_inputs_fn` on simulated CPU devices."""

  def test_every_device_generates_its_own_replica(self):
    """Verifies X0 and B are generated by one program spanning the mesh.

    The program has no collectives, so no device receives another device's
    inputs, and every device holds an identical replica of the seeded
    X0 ~ N(0, 1) and B ~ N(0, 1) / sqrt(k).
    """
    num_devices, m, k, seed = 4, 8, 16, 3
    mesh = _mesh(num_devices)
    inputs_fn = matmul.make_inputs_fn(
        mesh, m=m, k=k, in_dtype=jnp.bfloat16, seed=seed
    )
    x0, b = inputs_fn()

    compiled_hlo = inputs_fn.lower().compile().as_text()
    for collective in (
        "all-gather",
        "all-reduce",
        "all-to-all",
        "collective-permute",
        "reduce-scatter",
    ):
      self.assertNotIn(collective, compiled_hlo)

    k1, k2 = jax.random.split(jax.random.PRNGKey(seed), 2)
    references = (
        jax.random.normal(k1, (m, k)),
        jax.random.normal(k2, (k, k)) / np.sqrt(k),
    )
    for arr, reference in zip((x0, b), references):
      self.assertEqual(arr.shape, reference.shape)
      self.assertEqual(arr.dtype, jnp.bfloat16)
      self.assertTrue(arr.sharding.is_fully_replicated)
      self.assertEqual(arr.sharding.device_set, set(mesh.devices.flat))
      replicas = [np.asarray(s.data) for s in arr.addressable_shards]
      self.assertLen(replicas, num_devices)
      for replica in replicas[1:]:
        np.testing.assert_array_equal(replica, replicas[0])
      # The reference is float32; X0 and B are rounded to bfloat16.
      np.testing.assert_allclose(
          replicas[0].astype(np.float32),
          np.asarray(reference, dtype=np.float32),
          rtol=1e-2,
          atol=1e-2,
      )


class ChainFnTest(absltest.TestCase):
  """Tests for `make_chain_fn` on simulated CPU devices."""

  def test_each_device_keeps_its_own_final_x(self):
    """Verifies the chain returns each device's own final X.

    Device `bad` gets a corrupted replica of X0, so only its block of X may
    differ from the other devices'.
    """
    num_devices, m, k, chain_length, bad = 4, 8, 16, 3, 2
    mesh = _mesh(num_devices)
    x0 = jax.random.normal(jax.random.PRNGKey(0), (m, k)).astype(jnp.bfloat16)
    b = (jax.random.normal(jax.random.PRNGKey(1), (k, k)) / 4.0).astype(
        jnp.bfloat16
    )
    chain_fn = matmul.make_chain_fn(
        mesh, chain_length, jnp.bfloat16, jnp.bfloat16
    )
    x = chain_fn(
        _replicated_with_fault(x0, mesh, device_index=bad, flat_index=3, bit=6),
        _replicated_with_fault(b, mesh),
    )

    self.assertEqual(x.shape, (num_devices * m, k))
    self.assertEqual(x.dtype, jnp.bfloat16)

    x_blocks = {s.device: np.asarray(s.data) for s in x.addressable_shards}
    healthy = x_blocks[mesh.devices.flat[0]]
    np.testing.assert_allclose(
        healthy.astype(np.float32),
        np.asarray(
            _reference_chain(x0, b, chain_length, jnp.bfloat16, jnp.bfloat16),
            dtype=np.float32,
        ),
        rtol=2e-2,
        atol=2e-2,
    )
    for d, device in enumerate(mesh.devices.flat):
      block = x_blocks[device]
      self.assertEqual(block.shape, (m, k))
      if d == bad:
        self.assertFalse(np.array_equal(block, healthy))
      else:
        np.testing.assert_array_equal(block, healthy)


class GemmChainedBenchmarkTest(parameterized.TestCase):
  """End-to-end unit tests for GemmChainedParams and GemmChainedBenchmark."""

  def setUp(self):
    super().setUp()
    self._platform_patcher = mock.patch(
        "accelerator_microbenchmarks.core.platform.get_platform_info",
        return_value=test_report_utils.DEFAULT_TEST_PLATFORM_INFO,
    )
    self._platform_patcher.start()
    self.addCleanup(self._platform_patcher.stop)
    self.mesh = _mesh(8)

  def _benchmark(self, cfg, cls=matmul.GemmChainedBenchmark, **kwargs):
    return cls(
        config=cfg,
        hardware_spec=system.TPU7X_HARDWARE_SPEC,
        mesh=self.mesh,
        **kwargs,
    )

  @parameterized.named_parameters(
      ("m", "m", 0, 1),
      ("k", "k", 0, 1),
      ("seed", "seed", -1, 0),
      ("chain_length", "chain_length", 0, 1),
  )
  def test_params_out_of_range_values_raise_error(self, field, value, bound):
    """Verifies the bounds declared on GemmChainedParams fields."""
    with self.assertRaisesRegex(ValueError, f"{field} must be >= {bound}"):
      matmul.GemmChainedParams(**{field: value})

  @parameterized.named_parameters(
      ("int8_in", {"in_dtype": "int8"}, "in_dtype"),
      ("int8_out", {"out_dtype": "int8"}, "out_dtype"),
      ("int4_in", {"in_dtype": "int4"}, "in_dtype"),
      ("float64_out", {"out_dtype": "float64"}, "out_dtype"),
  )
  def test_params_reject_non_float_or_unsupported_width_dtypes(
      self, dtype_kwargs, field
  ):
    """Verifies integer, sub-byte and 64-bit dtypes are rejected."""
    with self.assertRaisesRegex(
        ValueError, rf"floating-point {field} with a bit width in \(8, 16, 32\)"
    ):
      matmul.GemmChainedParams(m=128, k=128, **dtype_kwargs)

  @parameterized.named_parameters(
      ("bfloat16", "bfloat16", "bfloat16"),
      ("float32", "float32", "float32"),
      ("float16", "float16", "float16"),
      ("fp8_to_bf16", "float8_e4m3fn", "bfloat16"),
  )
  def test_params_accept_supported_float_dtypes(self, in_dtype, out_dtype):
    """Verifies 8/16/32-bit floating-point dtypes are accepted."""
    cfg = matmul.GemmChainedParams(
        m=128, k=128, in_dtype=in_dtype, out_dtype=out_dtype
    )
    self.assertEqual((cfg.in_dtype, cfg.out_dtype), (in_dtype, out_dtype))

  def test_flops_bytes_tflops_and_run_identifier(self):
    """Verifies FLOPs, bytes and TFLOPs cover the whole chain; the run id."""
    chain_length, m, k = 5, 32, 64
    cfg = matmul.GemmChainedParams(
        m=m,
        k=k,
        in_dtype="bfloat16",
        out_dtype="float32",
        chain_length=chain_length,
    )
    bm = self._benchmark(cfg)
    chain_flops = chain_length * 2 * m * k * k
    self.assertEqual(bm.get_total_flops(), float(chain_flops))
    # bytes per step = 32*64*2 (A) + 64*64*2 (B) + 32*64*4 (Out) = 20480
    self.assertEqual(bm.get_total_bytes(), chain_length * 20480.0)
    self.assertAlmostEqual(
        bm.get_arithmetic_intensity(), (2 * m * k * k) / 20480.0
    )
    # TFLOPs divide the whole chain's FLOPs by the per-chain latency.
    latency_ms = 2.0
    metrics = bm.calculate_throughput_metrics(
        latency_ms=latency_ms, prefix=constants.TimingDomain.WALL_CLOCK
    )
    self.assertAlmostEqual(
        metrics["wall_clock_tflops_per_device"],
        chain_flops / (latency_ms / 1e3) / 1e12,
    )
    self.assertEqual(
        bm.get_run_identifier(), "m_32_k_64_bfloat16_to_float32_chain_5"
    )

  def test_compute_roofline_uses_in_dtype(self):
    """Verifies the compute roofline looks up peak TFLOPS by in_dtype."""
    bm = self._benchmark(
        matmul.GemmChainedParams(
            m=16, k=16, in_dtype="float8_e4m3fn", out_dtype="bfloat16"
        )
    )
    self.assertEqual(bm.roofline_mode, constants.RooflineMode.COMPUTE)
    self.assertEqual(bm.get_compute_dtype(), "float8_e4m3fn")

  def test_zero_latency_throughput_metrics(self):
    """Verifies a zero latency yields inf TFLOPS instead of dividing by zero."""
    bm = self._benchmark(matmul.GemmChainedParams(m=16, k=16))
    metrics = bm.calculate_throughput_metrics(
        latency_ms=0.0, prefix=constants.TimingDomain.WALL_CLOCK
    )
    self.assertEqual(metrics["wall_clock_tflops_per_device"], float("inf"))

  @parameterized.named_parameters(
      ("bfloat16", "bfloat16", "bfloat16"),
      ("fp8_to_bf16", "float8_e4m3fn", "bfloat16"),
  )
  def test_healthy_8_device_run_and_rerun_stability(self, in_dtype, out_dtype):
    """Verifies a healthy run matches across all devices and across reruns."""
    params = dict(
        m=16,
        k=16,
        in_dtype=in_dtype,
        out_dtype=out_dtype,
        chain_length=4,
        warmup_tries=1,
        num_runs=2,
    )
    m1 = (
        self._benchmark(matmul.GemmChainedParams(seed=42, **params))
        .run()
        .metrics
    )

    self.assertTrue(m1["all_devices_valid_checksum"])
    self.assertTrue(m1["intra_host_checksum_match"])
    self.assertTrue(m1["global_checksum_match"])
    self.assertEqual(m1["diverging_devices"], [])
    self.assertTrue(m1["checksum"].startswith("0x"))
    self.assertLen(m1["device_checksums"], 8)
    for idx, entry in enumerate(m1["device_checksums"]):
      self.assertEqual(entry["device_id"], idx)
      self.assertEqual(entry["checksum"], m1["checksum"])
      self.assertIsNone(entry["coords"])
      self.assertIsNone(entry["core_on_chip"])

    # Rerun with identical config produces the exact same checksum
    m2 = (
        self._benchmark(matmul.GemmChainedParams(seed=42, **params))
        .run()
        .metrics
    )
    self.assertEqual(m2["checksum"], m1["checksum"])

    # Rerun with different seed produces a different checksum
    m3 = (
        self._benchmark(matmul.GemmChainedParams(seed=99, **params))
        .run()
        .metrics
    )
    self.assertNotEqual(m3["checksum"], m1["checksum"])

  @parameterized.named_parameters(
      # (operand, start_step, device_index, flat_index, bit)
      ("x_at_first_step", "x", 0, 5, 3, 6),
      ("x_before_last_step", "x", 3, 5, 3, 6),
      ("b_corrupted_weight", "b", 0, 2, 7, 6),
  )
  def test_single_bit_fault_on_one_device_identifies_diverging_device(
      self, operand, start_step, device_index, flat_index, bit
  ):
    """Verifies a 1-bit fault on one device's replica flags only that device.

    The fault is injected by giving one device a corrupted copy of X (at chain
    step `start_step`) or of B; the benchmark itself has no fault hooks.
    """
    total_chain_length = 4
    cfg = matmul.GemmChainedParams(
        m=16,
        k=16,
        in_dtype="bfloat16",
        out_dtype="bfloat16",
        chain_length=total_chain_length - start_step,
        seed=7,
        warmup_tries=1,
        num_runs=2,
    )
    common = dict(
        cls=_CorruptedInputGemmChained,
        start_step=start_step,
        operand=operand,
        flat_index=flat_index,
        bit=bit,
    )
    healthy_checksum = (
        self._benchmark(cfg, device_index=None, **common)
        .run()
        .metrics["checksum"]
    )
    if start_step == 0:
      # Sanity check: the test subclass reproduces the production benchmark.
      self.assertEqual(
          self._benchmark(cfg).run().metrics["checksum"], healthy_checksum
      )

    fm = self._benchmark(cfg, device_index=device_index, **common).run().metrics

    self.assertTrue(fm["all_devices_valid_checksum"])
    self.assertIs(fm["intra_host_checksum_match"], False)
    self.assertIs(fm["global_checksum_match"], False)
    self.assertEqual(fm["checksum"], healthy_checksum)
    self.assertLen(fm["diverging_devices"], 1)
    div = fm["diverging_devices"][0]
    self.assertEqual(div["device_id"], device_index)
    self.assertEqual(div["process_index"], 0)
    self.assertEqual(div["consensus"], healthy_checksum)
    self.assertNotEqual(div["checksum"], healthy_checksum)

    # All other 7 devices in device_checksums must match healthy_checksum
    for entry in fm["device_checksums"]:
      if entry["device_id"] == device_index:
        self.assertEqual(entry["checksum"], div["checksum"])
      else:
        self.assertEqual(entry["checksum"], healthy_checksum)

  def test_checksum_and_readback_only_after_timed_loop(self):
    """Verifies the timed run_op returns X; checksum and readback come after."""
    m, k = 16, 16
    bm = self._benchmark(
        matmul.GemmChainedParams(
            m=m, k=k, chain_length=2, warmup_tries=2, num_runs=3
        )
    )
    bm.setup()
    inputs = bm.generate_inputs()
    # The timed op returns every device's final X, not its checksum.
    x = bm.run_op(*inputs)
    self.assertEqual(x.shape, (_NUM_CPU_DEVICES * m, k))
    self.assertEqual(x.dtype, jnp.bfloat16)

    with mock.patch.object(
        bm,
        "_checksum_fn",
        wraps=bm._checksum_fn,  # pylint: disable=protected-access
    ) as spy_checksum, mock.patch.object(
        checksum, "read_local_rows", wraps=checksum.read_local_rows
    ) as spy_read:
      bm.executor.run_warmup(inputs)
      bm.executor.execute(inputs, local_xprof_dir=None)
      # No checksum computation or D2H readback in warmup or the timed loop.
      self.assertEqual(spy_checksum.call_count, 0)
      self.assertEqual(spy_read.call_count, 0)
      metrics = bm.calculate_metrics([1.0, 1.0, 1.0])
      self.assertEqual(spy_checksum.call_count, 1)
      self.assertEqual(spy_read.call_count, 1)
    self.assertIs(metrics["global_checksum_match"], True)
    # The final X is released once its checksum has been computed.
    self.assertIsNone(bm._last_x)  # pylint: disable=protected-access

  def test_schema_coverage_and_report_output_files(self):
    """Verifies REPORT_SCHEMA and summary.csv / detailed.json output."""
    bm = self._benchmark(
        matmul.GemmChainedParams(
            m=16, k=16, chain_length=2, warmup_tries=1, num_runs=1
        )
    )
    bm.setup()
    inputs = bm.generate_inputs()
    bm.run_op(*inputs)

    self.assertEqual(
        [col for col, _ in matmul.GemmChainedBenchmark.REPORT_SCHEMA],
        [
            "in_dtype",
            "out_dtype",
            "m",
            "k",
            "chain_length",
            "all_devices_valid_checksum",
            "intra_host_checksum_match",
            "global_checksum_match",
            "total_flops",
            "wall_clock_p50_ms",
            "wall_clock_tflops_per_chip",
            "xprof_p50_ms",
            "xprof_tflops_per_chip",
        ],
    )
    test_report_utils.assert_schema_matches_output(
        self,
        bm,
        ignored_keys={
            # Checksum fields too wide for the console table.
            checksum.CHECKSUM,
            checksum.DEVICE_CHECKSUMS,
            checksum.DIVERGING_DEVICES,
        },
    )

    res = bm.run()
    with tempfile.TemporaryDirectory() as tmpdir:
      report.report_results([res], output_dir=tmpdir, print_table=True)
      with open(os.path.join(tmpdir, "detailed.json"), "r") as f:
        detailed = json.load(f)
      self.assertLen(detailed, 1)
      for key in checksum.CHECKSUM_METRIC_KEYS:
        self.assertIn(key, detailed[0]["metrics"])
      self.assertIsInstance(detailed[0]["metrics"]["device_checksums"], list)
      self.assertIsInstance(detailed[0]["metrics"]["diverging_devices"], list)

      with open(os.path.join(tmpdir, "summary.csv"), "r") as f:
        csv_rows = list(csv.DictReader(f))
      self.assertLen(csv_rows, 1)
      for key in checksum.CHECKSUM_METRIC_KEYS:
        self.assertIn(key, csv_rows[0])
      self.assertEqual(csv_rows[0]["checksum"], res.metrics["checksum"])
      self.assertEqual(csv_rows[0]["all_devices_valid_checksum"], "True")
      self.assertEqual(csv_rows[0]["intra_host_checksum_match"], "True")
      self.assertEqual(csv_rows[0]["global_checksum_match"], "True")
      self.assertEqual(csv_rows[0]["diverging_devices"], "[]")
      self.assertTrue(csv_rows[0]["device_checksums"].startswith("[{"))


